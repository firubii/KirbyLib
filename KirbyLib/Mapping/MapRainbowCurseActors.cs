        static readonly Dictionary<ActorKind, Type> ActorDataMap = new Dictionary<ActorKind, Type>()
        {
            { ActorKind.Gordo, typeof(BinGordo) }
        };

        public abstract class ActorData
        {
            public abstract void Read(EndianBinaryReader reader);
            public abstract void Write(EndianBinaryWriter writer, StringHelperContainer strings);
        }

        public class GenericActorData : ActorData
        {
            public byte[] Bytes;

            public override void Read(EndianBinaryReader reader) { }

            public override void Write(EndianBinaryWriter writer, StringHelperContainer strings)
            {
                writer.Write(Bytes);
                writer.WritePadding();
            }
        }

        public class BinGordo : ActorData
        {
            public int Unknown0;
            public int Unknown1;
            public float Unknown2;
            public int Unknown3;
            public int Unknown4;

            public override void Read(EndianBinaryReader reader)
            {
                Unknown0 = reader.ReadInt32();
                Unknown1 = reader.ReadInt32();
                Unknown2 = reader.ReadSingle();
                Unknown3 = reader.ReadInt32();
                Unknown4 = reader.ReadInt32();
            }

            public override void Write(EndianBinaryWriter writer, StringHelperContainer strings)
            {
                writer.Write(Unknown0);
                writer.Write(Unknown1);
                writer.Write(Unknown2);
                writer.Write(Unknown3);
                writer.Write(Unknown4);
            }
        }
